-- ============================================================
-- 1. SECUENCIA PARA NÚMERO DE VENTA
-- ============================================================

create sequence if not exists public.ventas_numero_seq
start with 1
increment by 1;


-- ============================================================
-- 2. TABLA VENTAS
-- ============================================================

create table if not exists public.ventas (
  id bigint generated by default as identity primary key,

  numero text not null unique,

  cliente_nombre text,

  subtotal numeric(14,2) not null default 0
    check (subtotal >= 0),

  descuento numeric(14,2) not null default 0
    check (descuento >= 0),

  total numeric(14,2) not null default 0
    check (total >= 0),

  estado text not null default 'completada'
    check (
      estado in (
        'completada',
        'anulada'
      )
    ),

  referencia text,

  creada_por uuid not null
    references auth.users(id),

  created_at timestamptz not null
    default now(),

  updated_at timestamptz not null
    default now(),

  anulada_at timestamptz,

  anulada_por uuid
    references auth.users(id),

  motivo_anulacion text
);


-- ============================================================
-- 3. DETALLE DE VENTAS
-- ============================================================

create table if not exists public.detalle_ventas (
  id bigint generated by default as identity primary key,

  venta_id bigint not null
    references public.ventas(id)
    on delete restrict,

  producto_id bigint not null
    references public.productos(id)
    on delete restrict,

  cantidad numeric(14,2) not null
    check (cantidad > 0),

  precio_unitario numeric(14,2) not null
    check (precio_unitario >= 0),

  subtotal numeric(14,2) not null
    check (subtotal >= 0),

  created_at timestamptz not null
    default now()
);


-- ============================================================
-- 4. PAGOS DE VENTA
-- ============================================================

create table if not exists public.pagos_venta (
  id bigint generated by default as identity primary key,

  venta_id bigint not null
    references public.ventas(id)
    on delete restrict,

  metodo_pago text not null
    check (
      metodo_pago in (
        'efectivo',
        'tarjeta',
        'transferencia'
      )
    ),

  monto numeric(14,2) not null
    check (monto > 0),

  monto_recibido numeric(14,2),

  cambio numeric(14,2) not null
    default 0
    check (cambio >= 0),

  referencia text,

  creado_por uuid not null
    references auth.users(id),

  created_at timestamptz not null
    default now()
);


-- ============================================================
-- 5. MOVIMIENTOS DE CAJA
-- ============================================================

create table if not exists public.movimientos_caja (
  id bigint generated by default as identity primary key,

  venta_id bigint
    references public.ventas(id)
    on delete restrict,

  tipo text not null
    check (
      tipo in (
        'ingreso',
        'egreso',
        'ajuste'
      )
    ),

  concepto text not null,

  metodo_pago text
    check (
      metodo_pago is null
      or metodo_pago in (
        'efectivo',
        'tarjeta',
        'transferencia'
      )
    ),

  monto numeric(14,2) not null
    check (monto > 0),

  referencia text,

  creado_por uuid not null
    references auth.users(id),

  created_at timestamptz not null
    default now()
);


-- ============================================================
