-- ============================================================
-- 11. FUNCIÓN REGISTRAR VENTA
--
-- p_items:
--
-- [
--   {
--     "producto_id": 1,
--     "cantidad": 2
--   },
--   {
--     "producto_id": 2,
--     "cantidad": 1
--   }
-- ]
--
-- ============================================================

create or replace function public.registrar_venta(
  p_items jsonb,
  p_metodo_pago text,
  p_monto_recibido numeric default null,
  p_cliente_nombre text default null,
  p_referencia text default null
)
returns table (
  venta_id bigint,
  numero text,
  total numeric,
  cambio numeric
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_usuario uuid;
  v_rol text;

  v_venta_id bigint;
  v_numero text;

  v_item jsonb;

  v_producto_id bigint;
  v_cantidad numeric(14,2);

  v_producto_nombre text;
  v_precio numeric(14,2);

  v_existencia_anterior numeric(14,2);
  v_existencia_nueva numeric(14,2);

  v_subtotal_linea numeric(14,2);
  v_total numeric(14,2) := 0;

  v_monto_recibido numeric(14,2);
  v_cambio numeric(14,2) := 0;
begin

  -- ========================================================
  -- VALIDAR USUARIO
  -- ========================================================

  v_usuario := auth.uid();

  if v_usuario is null then
    raise exception
      'Usuario no autenticado.';
  end if;


  -- ========================================================
  -- VALIDAR ROL
  -- ========================================================

  v_rol :=
    public.current_role_code();

  if v_rol is null
     or v_rol not in (
       'ventas',
       'gerencia'
     )
  then
    raise exception
      'El usuario no tiene permiso para registrar ventas.';
  end if;


  -- ========================================================
  -- VALIDAR ITEMS
  -- ========================================================

  if p_items is null
     or jsonb_typeof(p_items) <> 'array'
     or jsonb_array_length(p_items) = 0
  then
    raise exception
      'La venta debe contener al menos un producto.';
  end if;


  -- ========================================================
  -- VALIDAR MÉTODO DE PAGO
  -- ========================================================

  p_metodo_pago :=
    lower(
      trim(
        p_metodo_pago
      )
    );

  if p_metodo_pago not in (
    'efectivo',
    'tarjeta',
    'transferencia'
  )
  then
    raise exception
      'Método de pago no válido.';
  end if;


  -- ========================================================
  -- GENERAR NÚMERO DE VENTA
  -- ========================================================

  v_numero :=
    'V-' ||
    lpad(
      nextval(
        'public.ventas_numero_seq'
      )::text,
      6,
      '0'
    );


  -- ========================================================
  -- CREAR CABECERA
  -- ========================================================

  insert into public.ventas (
    numero,
    cliente_nombre,
    subtotal,
    descuento,
    total,
    estado,
    referencia,
    creada_por
  )
  values (
    v_numero,
    nullif(
      trim(
        p_cliente_nombre
      ),
      ''
    ),
    0,
    0,
    0,
    'completada',
    nullif(
      trim(
        p_referencia
      ),
      ''
    ),
    v_usuario
  )
  returning id
  into v_venta_id;


  -- ========================================================
  -- PROCESAR PRODUCTOS
  -- ========================================================

  for v_item
  in
    select value
    from jsonb_array_elements(
      p_items
    )
  loop

    -- ------------------------------------------------------
    -- OBTENER DATOS DEL ITEM
    -- ------------------------------------------------------

    begin
      v_producto_id :=
        (
          v_item
          ->> 'producto_id'
        )::bigint;

      v_cantidad :=
        (
          v_item
          ->> 'cantidad'
        )::numeric;
    exception
      when others then
        raise exception
          'Formato de producto inválido.';
    end;


    if v_producto_id is null then
      raise exception
        'Producto inválido.';
    end if;


    if v_cantidad is null
       or v_cantidad <= 0
    then
      raise exception
        'La cantidad debe ser mayor que cero.';
    end if;


    -- ------------------------------------------------------
    -- BLOQUEAR EXISTENCIA DEL PRODUCTO
    -- ------------------------------------------------------

    select
      p.nombre,
      p.precio_venta,
      e.cantidad
    into
      v_producto_nombre,
      v_precio,
      v_existencia_anterior
    from public.productos p
    join public.existencias e
      on e.producto_id = p.id
    where p.id = v_producto_id
      and p.activo = true
    for update of e;


    if not found then
      raise exception
        'Producto % no encontrado o inactivo.',
        v_producto_id;
    end if;


    -- ------------------------------------------------------
    -- VALIDAR EXISTENCIA
    -- ------------------------------------------------------

    if v_existencia_anterior
       < v_cantidad
    then
      raise exception
        'Existencia insuficiente para %. Disponible: %, solicitado: %.',
        v_producto_nombre,
        v_existencia_anterior,
        v_cantidad;
    end if;


    -- ------------------------------------------------------
    -- CALCULAR SUBTOTAL
    -- ------------------------------------------------------

    v_subtotal_linea :=
      round(
        v_precio *
        v_cantidad,
        2
      );

    v_total :=
      v_total +
      v_subtotal_linea;


    -- ------------------------------------------------------
    -- REGISTRAR DETALLE
    -- ------------------------------------------------------

    insert into public.detalle_ventas (
      venta_id,
      producto_id,
      cantidad,
      precio_unitario,
      subtotal
    )
    values (
      v_venta_id,
      v_producto_id,
      v_cantidad,
      v_precio,
      v_subtotal_linea
    );


    -- ------------------------------------------------------
    -- ACTUALIZAR INVENTARIO
    -- ------------------------------------------------------

    v_existencia_nueva :=
      v_existencia_anterior -
      v_cantidad;

    update public.existencias
    set cantidad =
      v_existencia_nueva
    where producto_id =
      v_producto_id;


    -- ------------------------------------------------------
    -- REGISTRAR MOVIMIENTO DE INVENTARIO
    -- ------------------------------------------------------

    insert into public.movimientos_inventario (
      producto_id,
      tipo,
      cantidad,
      cantidad_anterior,
      cantidad_nueva,
      motivo,
      referencia,
      creado_por
    )
    values (
      v_producto_id,
      'salida',
      v_cantidad,
      v_existencia_anterior,
      v_existencia_nueva,
      'Venta ' ||
        v_numero,
      v_numero,
      v_usuario
    );

  end loop;


  -- ========================================================
  -- ACTUALIZAR TOTAL DE LA VENTA
  -- ========================================================

  update public.ventas
  set
    subtotal = v_total,
    total = v_total
  where id =
    v_venta_id;


  -- ========================================================
  -- PROCESAR PAGO
  -- ========================================================

  if p_metodo_pago =
     'efectivo'
  then

    v_monto_recibido :=
      coalesce(
        p_monto_recibido,
        v_total
      );

    if v_monto_recibido <
       v_total
    then
      raise exception
        'Monto recibido insuficiente. Total: %, recibido: %.',
        v_total,
        v_monto_recibido;
    end if;

    v_cambio :=
      round(
        v_monto_recibido -
        v_total,
        2
      );

  else

    v_monto_recibido :=
      v_total;

    v_cambio := 0;

  end if;


  -- ========================================================
  -- REGISTRAR PAGO
  -- ========================================================

  insert into public.pagos_venta (
    venta_id,
    metodo_pago,
    monto,
    monto_recibido,
    cambio,
    referencia,
    creado_por
  )
  values (
    v_venta_id,
    p_metodo_pago,
    v_total,
    v_monto_recibido,
    v_cambio,
    nullif(
      trim(
        p_referencia
      ),
      ''
    ),
    v_usuario
  );


  -- ========================================================
  -- REGISTRAR INGRESO EN CAJA
  -- ========================================================

  insert into public.movimientos_caja (
    venta_id,
    tipo,
    concepto,
    metodo_pago,
    monto,
    referencia,
    creado_por
  )
  values (
    v_venta_id,
    'ingreso',
    'Venta ' ||
      v_numero,
    p_metodo_pago,
    v_total,
    v_numero,
    v_usuario
  );


  -- ========================================================
  -- RESULTADO
  -- ========================================================

  return query
  select
    v_venta_id,
    v_numero,
    v_total,
    v_cambio;

end;
$$;


-- ============================================================
-- 12. FUNCIÓN ANULAR VENTA
-- ============================================================

create or replace function public.anular_venta(
  p_venta_id bigint,
  p_motivo text default
    'Anulación de venta'
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_usuario uuid;
  v_rol text;

  v_numero text;
  v_total numeric(14,2);
  v_estado text;

  v_metodo_pago text;

  v_detalle record;

  v_existencia_anterior numeric(14,2);
  v_existencia_nueva numeric(14,2);
begin

  -- ========================================================
  -- VALIDAR USUARIO
  -- ========================================================

  v_usuario :=
    auth.uid();

  if v_usuario is null then
    raise exception
      'Usuario no autenticado.';
  end if;


  -- ========================================================
  -- VALIDAR ROL
  -- ========================================================

  v_rol :=
    public.current_role_code();

  if v_rol is null
     or v_rol not in (
       'ventas',
       'gerencia'
     )
  then
    raise exception
      'El usuario no tiene permiso para anular ventas.';
  end if;


  -- ========================================================
  -- OBTENER Y BLOQUEAR VENTA
  -- ========================================================

  select
    numero,
    total,
    estado
  into
    v_numero,
    v_total,
    v_estado
  from public.ventas
  where id =
    p_venta_id
  for update;


  if not found then
    raise exception
      'Venta no encontrada.';
  end if;


  if v_estado =
     'anulada'
  then
    raise exception
      'La venta ya se encuentra anulada.';
  end if;


  -- ========================================================
  -- RESTAURAR INVENTARIO
  -- ========================================================

  for v_detalle
  in
    select
      producto_id,
      cantidad
    from public.detalle_ventas
    where venta_id =
      p_venta_id
  loop

    select cantidad
    into v_existencia_anterior
    from public.existencias
    where producto_id =
      v_detalle.producto_id
    for update;


    if not found then
      raise exception
        'No existe registro de inventario para el producto %.',
        v_detalle.producto_id;
    end if;


    v_existencia_nueva :=
      v_existencia_anterior +
      v_detalle.cantidad;


    update public.existencias
    set cantidad =
      v_existencia_nueva
    where producto_id =
      v_detalle.producto_id;


    insert into public.movimientos_inventario (
      producto_id,
      tipo,
      cantidad,
      cantidad_anterior,
      cantidad_nueva,
      motivo,
      referencia,
      creado_por
    )
    values (
      v_detalle.producto_id,
      'entrada',
      v_detalle.cantidad,
      v_existencia_anterior,
      v_existencia_nueva,
      coalesce(
        nullif(
          trim(
            p_motivo
          ),
          ''
        ),
        'Anulación de venta'
      ),
      'ANULACION-' ||
        v_numero,
      v_usuario
    );

  end loop;


  -- ========================================================
  -- OBTENER MÉTODO DE PAGO
  -- ========================================================

  select metodo_pago
  into v_metodo_pago
  from public.pagos_venta
  where venta_id =
    p_venta_id
  order by id
  limit 1;


  -- ========================================================
  -- MARCAR VENTA COMO ANULADA
  -- ========================================================

  update public.ventas
  set
    estado =
      'anulada',

    anulada_at =
      now(),

    anulada_por =
      v_usuario,

    motivo_anulacion =
      coalesce(
        nullif(
          trim(
            p_motivo
          ),
          ''
        ),
        'Anulación de venta'
      )

  where id =
    p_venta_id;


  -- ========================================================
  -- REGISTRAR EGRESO EN CAJA
  -- ========================================================

  insert into public.movimientos_caja (
    venta_id,
    tipo,
    concepto,
    metodo_pago,
    monto,
    referencia,
    creado_por
  )
  values (
    p_venta_id,
    'egreso',
    'Anulación de venta ' ||
      v_numero,
    v_metodo_pago,
    v_total,
    'ANULACION-' ||
      v_numero,
    v_usuario
  );

end;
$$;


