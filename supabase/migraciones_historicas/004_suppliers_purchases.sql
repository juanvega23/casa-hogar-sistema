-- ============================================================
-- 7. FUNCIÓN REGISTRAR COMPRA
-- ============================================================

create or replace function public.registrar_compra(
  p_proveedor_id bigint,
  p_items jsonb,
  p_fecha_compra date default current_date,
  p_referencia_documento text default null,
  p_observaciones text default null
)
returns table (
  compra_id bigint,
  numero text,
  total numeric
)
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  v_rol text;

  v_compra_id bigint;
  v_numero text;
  v_total numeric(14,2) := 0;

  v_item jsonb;

  v_producto_id bigint;
  v_cantidad numeric(14,2);
  v_costo_unitario numeric(14,2);
  v_subtotal numeric(14,2);

  v_producto_nombre text;

  v_existencia_actual numeric(12,2);
  v_existencia_nueva numeric(12,2);
begin

  -- ==========================================================
  -- 1. VALIDAR ROL
  -- ==========================================================

  v_rol := public.current_role_code();

  if coalesce(v_rol, '') not in (
    'almacen',
    'administracion',
    'gerencia'
  ) then
    raise exception
      'No tiene permisos para registrar compras.';
  end if;


  -- ==========================================================
  -- 2. VALIDAR PROVEEDOR
  -- ==========================================================

  perform 1
  from public.proveedores
  where id = p_proveedor_id
    and activo = true;

  if not found then
    raise exception
      'El proveedor no existe o se encuentra inactivo.';
  end if;


  -- ==========================================================
  -- 3. VALIDAR DETALLE
  -- ==========================================================

  if p_items is null
     or jsonb_typeof(p_items) <> 'array'
     or jsonb_array_length(p_items) = 0 then

    raise exception
      'La compra debe contener al menos un producto.';
  end if;


  -- ==========================================================
  -- 4. NO PERMITIR PRODUCTOS REPETIDOS
  -- ==========================================================

  if exists (
    select 1
    from (
      select
        (item->>'producto_id')::bigint as producto_id,
        count(*) as cantidad_registros
      from jsonb_array_elements(p_items) as t(item)
      group by
        (item->>'producto_id')::bigint
      having count(*) > 1
    ) duplicados
  ) then

    raise exception
      'Un producto no puede repetirse dentro de la misma compra.';
  end if;


  -- ==========================================================
  -- 5. VALIDAR PRODUCTOS Y CALCULAR TOTAL
  -- ==========================================================

  for v_item in
    select value
    from jsonb_array_elements(p_items)
  loop

    begin

      v_producto_id :=
        (v_item->>'producto_id')::bigint;

      v_cantidad :=
        (v_item->>'cantidad')::numeric;

      v_costo_unitario :=
        (v_item->>'costo_unitario')::numeric;

    exception
      when others then
        raise exception
          'Existe un producto con datos inválidos dentro de la compra.';
    end;


    if v_producto_id is null then
      raise exception
        'Producto inválido.';
    end if;


    if v_cantidad is null
       or v_cantidad <= 0 then
      raise exception
        'La cantidad de compra debe ser mayor que cero.';
    end if;


    if v_costo_unitario is null
       or v_costo_unitario < 0 then
      raise exception
        'El costo unitario no puede ser negativo.';
    end if;


    select p.nombre
    into v_producto_nombre
    from public.productos p
    where p.id = v_producto_id
      and p.activo = true;

    if not found then
      raise exception
        'El producto % no existe o se encuentra inactivo.',
        v_producto_id;
    end if;


    v_subtotal :=
      round(
        v_cantidad * v_costo_unitario,
        2
      );


    v_total :=
      v_total + v_subtotal;

  end loop;


  -- ==========================================================
  -- 6. CREAR CABECERA DE COMPRA
  -- ==========================================================

  insert into public.compras (
    proveedor_id,
    fecha_compra,
    referencia_documento,
    observaciones,
    total,
    estado,
    creado_por
  )
  values (
    p_proveedor_id,

    coalesce(
      p_fecha_compra,
      current_date
    ),

    nullif(
      trim(
        coalesce(
          p_referencia_documento,
          ''
        )
      ),
      ''
    ),

    nullif(
      trim(
        coalesce(
          p_observaciones,
          ''
        )
      ),
      ''
    ),

    v_total,
    'registrada',
    auth.uid()
  )
  returning
    id,
    compras.numero
  into
    v_compra_id,
    v_numero;


  -- ==========================================================
  -- 7. REGISTRAR DETALLE Y ENTRADAS DE INVENTARIO
  -- ==========================================================

  for v_item in
    select value
    from jsonb_array_elements(p_items)
  loop

    v_producto_id :=
      (v_item->>'producto_id')::bigint;

    v_cantidad :=
      (v_item->>'cantidad')::numeric;

    v_costo_unitario :=
      (v_item->>'costo_unitario')::numeric;

    v_subtotal :=
      round(
        v_cantidad * v_costo_unitario,
        2
      );


    -- --------------------------------------------------------
    -- Registrar detalle
    -- --------------------------------------------------------

    insert into public.detalle_compras (
      compra_id,
      producto_id,
      cantidad,
      costo_unitario,
      subtotal
    )
    values (
      v_compra_id,
      v_producto_id,
      v_cantidad,
      v_costo_unitario,
      v_subtotal
    );


    -- --------------------------------------------------------
    -- Asegurar existencia
    -- --------------------------------------------------------

    insert into public.existencias (
      producto_id,
      cantidad
    )
    values (
      v_producto_id,
      0
    )
    on conflict (producto_id) do nothing;


    -- --------------------------------------------------------
    -- Bloquear existencia
    -- --------------------------------------------------------

    select e.cantidad
    into v_existencia_actual
    from public.existencias e
    where e.producto_id = v_producto_id
    for update;


    if not found then
      raise exception
        'No fue posible obtener la existencia del producto %.',
        v_producto_id;
    end if;


    -- --------------------------------------------------------
    -- Calcular nueva existencia
    -- --------------------------------------------------------

    v_existencia_nueva :=
      v_existencia_actual + v_cantidad;


    -- --------------------------------------------------------
    -- Actualizar inventario
    -- --------------------------------------------------------

    update public.existencias
    set cantidad = v_existencia_nueva
    where producto_id = v_producto_id;


    -- --------------------------------------------------------
    -- Registrar movimiento de inventario
    -- --------------------------------------------------------

    insert into public.movimientos_inventario (
      producto_id,
      tipo,
      cantidad,
      cantidad_anterior,
      cantidad_nueva,
      motivo,
      referencia,
      creado_por
    )
    values (
      v_producto_id,
      'entrada',
      v_cantidad,
      v_existencia_actual,
      v_existencia_nueva,
      'Entrada por compra ' || v_numero,
      v_numero,
      auth.uid()
    );

  end loop;


  -- ==========================================================
  -- 8. RESULTADO
  -- ==========================================================

  return query
  select
    v_compra_id,
    v_numero,
    v_total;

end;
$$;


-- ============================================================
-- 8. FUNCIÓN ANULAR COMPRA
-- ============================================================

create or replace function public.anular_compra(
  p_compra_id bigint,
  p_motivo text
)
returns void
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  v_rol text;

  v_compra record;
  v_detalle record;

  v_existencia_actual numeric(12,2);
  v_existencia_nueva numeric(12,2);
begin

  -- ==========================================================
  -- 1. VALIDAR AUTORIZACIÓN
  -- ==========================================================

  v_rol := public.current_role_code();

  if coalesce(v_rol, '') not in (
    'administracion',
    'gerencia'
  ) then
    raise exception
      'Solo Administración o Gerencia pueden anular una compra.';
  end if;


  -- ==========================================================
  -- 2. VALIDAR MOTIVO
  -- ==========================================================

  if p_motivo is null
     or length(trim(p_motivo)) < 3 then
    raise exception
      'Debe indicar un motivo válido para anular la compra.';
  end if;


  -- ==========================================================
  -- 3. OBTENER Y BLOQUEAR COMPRA
  -- ==========================================================

  select
    c.id,
    c.numero,
    c.estado
  into v_compra
  from public.compras c
  where c.id = p_compra_id
  for update;


  if not found then
    raise exception
      'La compra indicada no existe.';
  end if;


  if v_compra.estado = 'anulada' then
    raise exception
      'La compra % ya se encuentra anulada.',
      v_compra.numero;
  end if;


  -- ==========================================================
  -- 4. REVERTIR INVENTARIO
  -- ==========================================================

  for v_detalle in
    select
      dc.producto_id,
      dc.cantidad
    from public.detalle_compras dc
    where dc.compra_id = p_compra_id
  loop

    -- --------------------------------------------------------
    -- Obtener y bloquear existencia
    -- --------------------------------------------------------

    select e.cantidad
    into v_existencia_actual
    from public.existencias e
    where e.producto_id = v_detalle.producto_id
    for update;


    if not found then
      raise exception
        'No existe registro de inventario para el producto %.',
        v_detalle.producto_id;
    end if;


    -- --------------------------------------------------------
    -- Validar existencia suficiente para revertir
    -- --------------------------------------------------------

    if v_existencia_actual < v_detalle.cantidad then
      raise exception
        'No se puede anular la compra %. Existencia insuficiente para el producto %. Disponible: %, requerido: %.',
        v_compra.numero,
        v_detalle.producto_id,
        v_existencia_actual,
        v_detalle.cantidad;
    end if;


    -- --------------------------------------------------------
    -- Calcular existencia posterior
    -- --------------------------------------------------------

    v_existencia_nueva :=
      v_existencia_actual - v_detalle.cantidad;


    -- --------------------------------------------------------
    -- Actualizar existencia
    -- --------------------------------------------------------

    update public.existencias
    set cantidad = v_existencia_nueva
    where producto_id = v_detalle.producto_id;


    -- --------------------------------------------------------
    -- Registrar movimiento de reversión
    -- --------------------------------------------------------

    insert into public.movimientos_inventario (
      producto_id,
      tipo,
      cantidad,
      cantidad_anterior,
      cantidad_nueva,
      motivo,
      referencia,
      creado_por
    )
    values (
      v_detalle.producto_id,
      'salida',
      v_detalle.cantidad,
      v_existencia_actual,
      v_existencia_nueva,
      'Anulación de compra ' || v_compra.numero,
      'ANULACION-' || v_compra.numero,
      auth.uid()
    );

  end loop;


  -- ==========================================================
  -- 5. MARCAR COMPRA COMO ANULADA
  -- ==========================================================

  update public.compras
  set
    estado = 'anulada',
    motivo_anulacion = trim(p_motivo),
    anulada_por = auth.uid(),
    anulada_at = now()
  where id = p_compra_id;

end;
$$;


