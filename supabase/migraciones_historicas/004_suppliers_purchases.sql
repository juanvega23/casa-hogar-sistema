-- ============================================================
-- 1. SECUENCIAS
-- ============================================================

create sequence if not exists public.proveedor_codigo_seq
start with 1
increment by 1;

create sequence if not exists public.compra_numero_seq
start with 1
increment by 1;


-- ============================================================
-- 2. PROVEEDORES
-- ============================================================

create table if not exists public.proveedores (
  id bigint generated by default as identity primary key,

  codigo text not null unique
    default (
      'PROV-' ||
      lpad(
        nextval('public.proveedor_codigo_seq')::text,
        6,
        '0'
      )
    ),

  nombre text not null,
  ruc text,
  contacto text,
  telefono text,
  email text,
  direccion text,

  activo boolean not null default true,

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  constraint proveedores_nombre_check
    check (length(trim(nombre)) >= 2)
);


-- ============================================================
-- 3. COMPRAS
-- ============================================================

create table if not exists public.compras (
  id bigint generated by default as identity primary key,

  numero text not null unique
    default (
      'C-' ||
      lpad(
        nextval('public.compra_numero_seq')::text,
        6,
        '0'
      )
    ),

  proveedor_id bigint not null
    references public.proveedores(id)
    on update restrict
    on delete restrict,

  fecha_compra date not null default current_date,

  referencia_documento text,
  observaciones text,

  total numeric(14,2) not null default 0,

  estado text not null default 'registrada',

  creado_por uuid
    references auth.users(id)
    on delete set null,

  anulada_por uuid
    references auth.users(id)
    on delete set null,

  anulada_at timestamptz,
  motivo_anulacion text,

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  constraint compras_total_check
    check (total >= 0),

  constraint compras_estado_check
    check (
      estado in (
        'registrada',
        'anulada'
      )
    )
);


-- ============================================================
-- 4. DETALLE DE COMPRAS
-- ============================================================

create table if not exists public.detalle_compras (
  id bigint generated by default as identity primary key,

  compra_id bigint not null
    references public.compras(id)
    on update cascade
    on delete cascade,

  producto_id bigint not null
    references public.productos(id)
    on update restrict
    on delete restrict,

  cantidad numeric(14,2) not null,

  costo_unitario numeric(14,2) not null,

  subtotal numeric(14,2) not null,

  created_at timestamptz not null default now(),

  constraint detalle_compras_cantidad_check
    check (cantidad > 0),

  constraint detalle_compras_costo_check
    check (costo_unitario >= 0),

  constraint detalle_compras_subtotal_check
    check (subtotal >= 0),

  constraint detalle_compras_producto_unico
    unique (
      compra_id,
      producto_id
    )
);


-- ============================================================
