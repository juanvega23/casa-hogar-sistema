-- ============================================================
-- 1. SECUENCIA
-- ============================================================

create sequence if not exists public.recepcion_compra_numero_seq
start with 1
increment by 1;


-- ============================================================
-- 2. RECEPCIONES DE COMPRA
-- ============================================================

create table if not exists public.recepciones_compra (
  id bigint generated by default as identity primary key,

  numero text not null unique
    default (
      'RC-' ||
      lpad(
        nextval('public.recepcion_compra_numero_seq')::text,
        6,
        '0'
      )
    ),

  compra_id bigint not null unique
    references public.compras(id)
    on delete restrict,

  fecha_recepcion date not null
    default current_date,

  observaciones text,

  recibido_por uuid
    references auth.users(id)
    on delete set null,

  created_at timestamptz not null
    default now(),

  updated_at timestamptz not null
    default now()
);


-- ============================================================
-- 3. DETALLE DE RECEPCIÓN
-- ============================================================

create table if not exists public.detalle_recepciones_compra (
  id bigint generated by default as identity primary key,

  recepcion_id bigint not null
    references public.recepciones_compra(id)
    on delete cascade,

  producto_id bigint not null
    references public.productos(id)
    on delete restrict,

  cantidad_recibida numeric(14,2) not null,

  created_at timestamptz not null
    default now(),

  constraint detalle_recepcion_cantidad_check
    check (cantidad_recibida > 0),

  constraint detalle_recepcion_producto_unique
    unique (
      recepcion_id,
      producto_id
    )
);


-- ============================================================
-- 4. TRIGGER UPDATED_AT
-- ============================================================

drop trigger if exists set_recepciones_compra_updated_at
on public.recepciones_compra;

create trigger set_recepciones_compra_updated_at
before update on public.recepciones_compra
for each row
execute function public.set_updated_at();


-- ============================================================
-- 5. ÍNDICES
-- ============================================================

create index if not exists idx_recepciones_compra_compra_id
on public.recepciones_compra(compra_id);

create index if not exists idx_detalle_recepcion_producto_id
on public.detalle_recepciones_compra(producto_id);