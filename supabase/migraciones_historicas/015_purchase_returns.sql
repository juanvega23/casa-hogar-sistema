-- ============================================================
-- 1. SECUENCIA
-- ============================================================

create sequence if not exists
public.devolucion_compra_numero_seq
start with 1
increment by 1;


-- ============================================================
-- 2. ENCABEZADO DE DEVOLUCIÓN
-- ============================================================

create table if not exists
public.devoluciones_compra (
  id bigint generated by default as identity
    primary key,

  numero text
    not null
    unique
    default (
      'DC-' ||
      lpad(
        nextval(
          'public.devolucion_compra_numero_seq'
        )::text,
        6,
        '0'
      )
    ),

  compra_id bigint
    not null
    references public.compras(id)
    on delete restrict,

  fecha_devolucion date
    not null
    default current_date,

  motivo text
    not null,

  observaciones text,

  creado_por uuid
    references auth.users(id)
    on delete set null,

  created_at timestamptz
    not null
    default now(),

  updated_at timestamptz
    not null
    default now(),

  constraint devoluciones_compra_motivo_check
    check (
      length(trim(motivo)) >= 3
    )
);


-- ============================================================
-- 3. DETALLE DE DEVOLUCIÓN
-- ============================================================

create table if not exists
public.detalle_devoluciones_compra (
  id bigint generated by default as identity
    primary key,

  devolucion_id bigint
    not null
    references public.devoluciones_compra(id)
    on delete cascade,

  producto_id bigint
    not null
    references public.productos(id)
    on delete restrict,

  cantidad_devuelta numeric(14,2)
    not null,

  created_at timestamptz
    not null
    default now(),

  constraint detalle_devoluciones_compra_cantidad_check
    check (
      cantidad_devuelta > 0
    ),

  constraint detalle_devoluciones_compra_unique
    unique (
      devolucion_id,
      producto_id
    )
);


-- ============================================================
-- 4. ÍNDICES
-- ============================================================

create index if not exists
idx_devoluciones_compra_compra
on public.devoluciones_compra(compra_id);


create index if not exists
idx_devoluciones_compra_fecha
on public.devoluciones_compra(fecha_devolucion);


create index if not exists
idx_detalle_devoluciones_producto
on public.detalle_devoluciones_compra(producto_id);


-- ============================================================
-- 5. UPDATED_AT
-- ============================================================

drop trigger if exists
set_devoluciones_compra_updated_at
on public.devoluciones_compra;


create trigger
set_devoluciones_compra_updated_at
before update
on public.devoluciones_compra
for each row
execute function public.set_updated_at();


-- ============================================================
-- 6. RLS
-- ============================================================

alter table public.devoluciones_compra
enable row level security;


alter table public.detalle_devoluciones_compra
enable row level security;


grant select
on public.devoluciones_compra
to authenticated;


grant select
on public.detalle_devoluciones_compra
to authenticated;


drop policy if exists
"devoluciones_compra_select"
on public.devoluciones_compra;


create policy
"devoluciones_compra_select"
on public.devoluciones_compra
for select
to authenticated
using (
  public.current_role_code() in (
    'almacen',
    'administracion',
    'gerencia'
  )
);


drop policy if exists
"detalle_devoluciones_compra_select"
on public.detalle_devoluciones_compra;


create policy
"detalle_devoluciones_compra_select"
on public.detalle_devoluciones_compra
for select
to authenticated
using (
  public.current_role_code() in (
    'almacen',
    'administracion',
    'gerencia'
  )
);


-- ============================================================
-- 7. FUNCIÓN REGISTRAR DEVOLUCIÓN
-- ============================================================

create or replace function public.registrar_devolucion_compra(
  p_compra_id bigint,
  p_items jsonb,
  p_motivo text,
  p_fecha_devolucion date default current_date,
  p_observaciones text default null
)
returns table(
  devolucion_id bigint,
  numero text
)
language plpgsql
security definer
set search_path to 'public', 'auth'
as $function$
declare
  v_rol text;

  v_compra record;

  v_devolucion_id bigint;
  v_numero_devolucion text;

  v_item jsonb;

  v_producto_id bigint;
  v_cantidad_devuelta numeric(14,2);

  v_cantidad_recibida numeric(14,2);
  v_cantidad_ya_devuelta numeric(14,2);
  v_cantidad_disponible_devolver numeric(14,2);

  v_producto_nombre text;
  v_unidad_medida text;

  v_existencia_actual numeric(12,2);
  v_existencia_nueva numeric(12,2);
begin

  -- ==========================================================
  -- 1. VALIDAR ROL
  -- ==========================================================

  v_rol :=
    public.current_role_code();


  if coalesce(
    v_rol,
    ''
  ) not in (
    'almacen',
    'administracion'
  ) then

    raise exception
      'No tiene permisos para registrar devoluciones de compra.';

  end if;


  -- ==========================================================
  -- 2. VALIDAR MOTIVO
  -- ==========================================================

  if p_motivo is null
     or length(
       trim(p_motivo)
     ) < 3 then

    raise exception
      'Debe indicar un motivo válido para la devolución.';

  end if;


  -- ==========================================================
  -- 3. OBTENER COMPRA
  -- ==========================================================

  select
    c.id,
    c.numero,
    c.estado
  into
    v_compra
  from public.compras c
  where c.id =
    p_compra_id
  for update;


  if not found then

    raise exception
      'La compra indicada no existe.';

  end if;


  if v_compra.estado <>
     'recibida' then

    raise exception
      'Solo pueden devolverse productos de una compra recibida. Compra: %.',
      v_compra.numero;

  end if;


  -- ==========================================================
  -- 4. VALIDAR ITEMS
  -- ==========================================================

  if p_items is null
     or jsonb_typeof(
       p_items
     ) <> 'array'
     or jsonb_array_length(
       p_items
     ) = 0 then

    raise exception
      'La devolución debe contener al menos un producto.';

  end if;


  -- Evitar productos repetidos
  if exists (
    select 1
    from (
      select
        (
          item->>'producto_id'
        )::bigint
          as producto_id,

        count(*)
          as cantidad_registros

      from jsonb_array_elements(
        p_items
      ) as t(item)

      group by
        (
          item->>'producto_id'
        )::bigint

      having count(*) > 1
    ) duplicados
  ) then

    raise exception
      'Un producto no puede repetirse dentro de la devolución.';

  end if;


  -- ==========================================================
  -- 5. VALIDAR CADA PRODUCTO
  -- ==========================================================

  for v_item in
    select value
    from jsonb_array_elements(
      p_items
    )
  loop

    begin

      v_producto_id :=
        (
          v_item->>'producto_id'
        )::bigint;


      v_cantidad_devuelta :=
        (
          v_item->>'cantidad_devuelta'
        )::numeric;

    exception
      when others then

        raise exception
          'Existe un producto con datos inválidos en la devolución.';

    end;


    if v_producto_id is null then

      raise exception
        'Producto inválido.';

    end if;


    if v_cantidad_devuelta is null
       or v_cantidad_devuelta <= 0 then

      raise exception
        'La cantidad a devolver debe ser mayor que cero.';

    end if;


    -- ----------------------------------------------------------
    -- Cantidad que realmente fue recibida
    -- ----------------------------------------------------------

    select
      drc.cantidad_recibida,
      p.nombre,
      p.unidad_medida
    into
      v_cantidad_recibida,
      v_producto_nombre,
      v_unidad_medida
    from public.recepciones_compra rc

    join public.detalle_recepciones_compra drc
      on drc.recepcion_id =
         rc.id

    join public.productos p
      on p.id =
         drc.producto_id

    where rc.compra_id =
          p_compra_id

      and drc.producto_id =
          v_producto_id;


    if not found then

      raise exception
        'El producto % no pertenece a la recepción de la compra %.',
        v_producto_id,
        v_compra.numero;

    end if;


    -- ----------------------------------------------------------
    -- Cantidad devuelta anteriormente
    -- ----------------------------------------------------------

    select
      coalesce(
        sum(
          ddc.cantidad_devuelta
        ),
        0
      )
    into
      v_cantidad_ya_devuelta
    from public.devoluciones_compra dc

    join public.detalle_devoluciones_compra ddc
      on ddc.devolucion_id =
         dc.id

    where dc.compra_id =
          p_compra_id

      and ddc.producto_id =
          v_producto_id;


    v_cantidad_disponible_devolver :=
      v_cantidad_recibida -
      v_cantidad_ya_devuelta;


    if v_cantidad_devuelta >
       v_cantidad_disponible_devolver then

      raise exception
        'No puede devolver % unidades de %. Disponible para devolución: %.',
        v_cantidad_devuelta,
        v_producto_nombre,
        v_cantidad_disponible_devolver;

    end if;


    -- ----------------------------------------------------------
    -- Validar cantidades enteras para unidad
    -- ----------------------------------------------------------

    if lower(
      trim(
        v_unidad_medida
      )
    ) = 'unidad'
       and
       v_cantidad_devuelta <>
       trunc(
         v_cantidad_devuelta
       ) then

      raise exception
        'La cantidad a devolver de % debe ser un número entero.',
        v_producto_nombre;

    end if;


    -- ----------------------------------------------------------
    -- Validar existencia física
    -- ----------------------------------------------------------

    select
      e.cantidad
    into
      v_existencia_actual
    from public.existencias e

    where e.producto_id =
          v_producto_id

    for update;


    if not found then

      raise exception
        'No existe inventario para el producto %.',

        v_producto_nombre;

    end if;


    if v_existencia_actual <
       v_cantidad_devuelta then

      raise exception
        'No existe suficiente inventario para devolver %. Disponible: %, requerido: %.',
        v_producto_nombre,
        v_existencia_actual,
        v_cantidad_devuelta;

    end if;

  end loop;


  -- ==========================================================
  -- 6. CREAR DEVOLUCIÓN
  -- ==========================================================

  insert into public.devoluciones_compra (
    compra_id,
    fecha_devolucion,
    motivo,
    observaciones,
    creado_por
  )
  values (
    p_compra_id,

    coalesce(
      p_fecha_devolucion,
      current_date
    ),

    trim(
      p_motivo
    ),

    nullif(
      trim(
        coalesce(
          p_observaciones,
          ''
        )
      ),
      ''
    ),

    auth.uid()
  )
  returning
    id,
    devoluciones_compra.numero
  into
    v_devolucion_id,
    v_numero_devolucion;


  -- ==========================================================
  -- 7. DETALLE + SALIDA DE INVENTARIO
  -- ==========================================================

  for v_item in
    select value
    from jsonb_array_elements(
      p_items
    )
  loop

    v_producto_id :=
      (
        v_item->>'producto_id'
      )::bigint;


    v_cantidad_devuelta :=
      (
        v_item->>'cantidad_devuelta'
      )::numeric;


    -- Guardar detalle
    insert into public.detalle_devoluciones_compra (
      devolucion_id,
      producto_id,
      cantidad_devuelta
    )
    values (
      v_devolucion_id,
      v_producto_id,
      v_cantidad_devuelta
    );


    -- Bloquear existencia
    select
      e.cantidad
    into
      v_existencia_actual
    from public.existencias e

    where e.producto_id =
          v_producto_id

    for update;


    v_existencia_nueva :=
      v_existencia_actual -
      v_cantidad_devuelta;


    -- Actualizar inventario
    update public.existencias
    set
      cantidad =
        v_existencia_nueva
    where producto_id =
          v_producto_id;


    -- Kardex
    insert into public.movimientos_inventario (
      producto_id,
      tipo,
      cantidad,
      cantidad_anterior,
      cantidad_nueva,
      motivo,
      referencia,
      creado_por
    )
    values (
      v_producto_id,
      'salida',
      v_cantidad_devuelta,
      v_existencia_actual,
      v_existencia_nueva,

      'Devolución de compra ' ||
      v_compra.numero,

      v_numero_devolucion,

      auth.uid()
    );

  end loop;


  -- ==========================================================
  -- 8. RESULTADO
  -- ==========================================================

  return query
  select
    v_devolucion_id,
    v_numero_devolucion;

end;
$function$;


