-- =========================================================
-- 3. TABLA DE PERFILES
-- =========================================================

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  nombre_completo text,
  role_id bigint references public.roles(id) on delete restrict,
  activo boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index profiles_role_id_idx
on public.profiles(role_id);

alter table public.profiles enable row level security;


-- =========================================================
-- 4. PERMISOS PARA DATA API
-- =========================================================

revoke all on table public.roles from anon, authenticated;
revoke all on table public.profiles from anon, authenticated;

grant select on table public.roles to authenticated;
grant select on table public.profiles to authenticated;


-- =========================================================
-- 5. POLÍTICAS RLS
-- =========================================================

create policy "Usuarios autenticados pueden consultar roles activos"
on public.roles
for select
to authenticated
using (activo = true);

create policy "Usuario puede consultar su propio perfil"
on public.profiles
for select
to authenticated
using ((select auth.uid()) = id);


-- =========================================================
-- 6. ACTUALIZACIÓN AUTOMÁTICA DE updated_at
-- =========================================================

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger set_profiles_updated_at
before update on public.profiles
for each row
execute function public.set_updated_at();


-- =========================================================
-- 7. CREACIÓN AUTOMÁTICA DE PERFIL
-- =========================================================

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (
    id,
    nombre_completo
  )
  values (
    new.id,
    coalesce(
      new.raw_user_meta_data ->> 'full_name',
      new.raw_user_meta_data ->> 'name'
    )
  );

  return new;
end;
$$;

create trigger on_auth_user_created
after insert on auth.users
for each row
execute function public.handle_new_user();