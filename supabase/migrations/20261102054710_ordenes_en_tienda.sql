REVOKE ALL ON FUNCTION public.facturar_orden_tienda(text, jsonb, text, bigint, text, date) FROM PUBLIC, anon, service_role;

GRANT EXECUTE ON FUNCTION public.crear_orden_tienda(jsonb, text) TO anon;
GRANT EXECUTE ON FUNCTION public.crear_orden_tienda(jsonb, text) TO authenticated;
GRANT EXECUTE ON FUNCTION public.orden_tienda_para_venta(text) TO authenticated;
GRANT EXECUTE ON FUNCTION public.facturar_orden_tienda(text, jsonb, text, bigint, text, date) TO authenticated;

COMMIT;
