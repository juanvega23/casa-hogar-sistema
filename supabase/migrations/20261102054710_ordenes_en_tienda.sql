-- ==========================================================
-- ORDEN EN TIENDA (cliente dentro de la ferretería)
--
-- El cliente arma su carrito en la tienda en línea desde su
-- celular y elige "Estoy en la ferretería: pagar en caja".
-- Recibe un código corto (ej. T7K4Q9), sin necesidad de cuenta.
-- En el mostrador el Vendedor escribe el código en
-- "Registrar venta", se carga la lista y registra la venta.
--
-- La orden NO aparta inventario ni fija precios: el precio y
-- el descuento de inventario son los de registrar_venta() en
-- el momento de facturar. Vence a las 24 horas.
--
-- Funciones:
--   crear_orden_tienda(items, nombre)  → anon y clientes web
--   orden_tienda_para_venta(codigo)    → vendedor
--   facturar_orden_tienda(...)         → vendedor (registra la
--                                        venta y cierra la orden
--                                        en una sola transacción)
-- ==========================================================

BEGIN;


-- ---------------------------------------------------------
-- 1. TABLAS
-- ---------------------------------------------------------

CREATE TABLE IF NOT EXISTS public.ordenes_tienda (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo text NOT NULL,
  cliente_web_id uuid REFERENCES public.clientes_web(id) ON DELETE SET NULL,
  cliente_nombre text,
  total_estimado numeric(14,2) NOT NULL DEFAULT 0,
  estado text NOT NULL DEFAULT 'abierta',
  venta_id bigint REFERENCES public.ventas(id),
  facturada_por uuid REFERENCES auth.users(id),
  facturada_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  expira_at timestamptz NOT NULL DEFAULT (now() + interval '24 hours'),
  CONSTRAINT ordenes_tienda_codigo_unique UNIQUE (codigo),
  CONSTRAINT ordenes_tienda_codigo_formato CHECK (codigo ~ '^[A-Z0-9]{6}$'),
  CONSTRAINT ordenes_tienda_estado_check CHECK (estado IN ('abierta', 'facturada'))
);

CREATE TABLE IF NOT EXISTS public.detalle_ordenes_tienda (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  orden_id bigint NOT NULL REFERENCES public.ordenes_tienda(id) ON DELETE CASCADE,
  producto_id bigint NOT NULL REFERENCES public.productos(id),
  cantidad numeric(14,2) NOT NULL CHECK (cantidad > 0),
  CONSTRAINT detalle_ordenes_tienda_unico UNIQUE (orden_id, producto_id)
);

CREATE INDEX IF NOT EXISTS ordenes_tienda_created_at_idx
  ON public.ordenes_tienda (created_at);

-- Solo se usan a través de las funciones: sin acceso directo.
ALTER TABLE public.ordenes_tienda ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.detalle_ordenes_tienda ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.ordenes_tienda FROM PUBLIC, anon, authenticated, service_role;
REVOKE ALL ON TABLE public.detalle_ordenes_tienda FROM PUBLIC, anon, authenticated, service_role;


-- ---------------------------------------------------------
-- 2. CREAR ORDEN (tienda, con o sin cuenta)
-- ---------------------------------------------------------

CREATE OR REPLACE FUNCTION public.crear_orden_tienda(
  p_items jsonb,
  p_nombre text DEFAULT NULL
)
RETURNS TABLE(codigo text, total_estimado numeric, expira_at timestamptz)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public', 'auth'
AS $$
DECLARE
  -- Sin 0/O, 1/I/L, 2/Z, 5/S, 8/B: se dictan y se leen sin confusión
  v_alfabeto constant text := 'ACDEFGHJKMNPQRTUVWXY34679';
  v_uid uuid := auth.uid();
  v_cliente_id uuid;
  v_nombre text;
  v_codigo text;
  v_orden_id bigint;
  v_expira timestamptz;
  v_item jsonb;
  v_producto_id bigint;
  v_cantidad numeric(14,2);
  v_producto public.productos%ROWTYPE;
  v_existencia numeric(14,2);
  v_total numeric(14,2) := 0;
  v_intento int := 0;
BEGIN
  -- Solo visitantes o clientes de la tienda (no cuentas de personal)
  IF v_uid IS NOT NULL THEN
    IF public.tipo_cuenta_actual() <> 'cliente_web' THEN
      RAISE EXCEPTION 'Esta cuenta no pertenece a la tienda en línea.';
    END IF;
    v_cliente_id := v_uid;
  END IF;

  IF p_items IS NULL
     OR jsonb_typeof(p_items) <> 'array'
     OR jsonb_array_length(p_items) = 0 THEN
    RAISE EXCEPTION 'La orden debe contener productos.';
  END IF;

  IF jsonb_array_length(p_items) > 40 THEN
    RAISE EXCEPTION 'La orden admite como máximo 40 productos distintos.';
  END IF;

  -- Freno básico contra abuso desde el acceso público
  IF (SELECT count(*) FROM public.ordenes_tienda o
      WHERE o.created_at > now() - interval '10 minutes') >= 100 THEN
    RAISE EXCEPTION 'Hay demasiadas órdenes en este momento. Intentá de nuevo en unos minutos.';
  END IF;

  v_nombre := nullif(left(trim(coalesce(p_nombre, '')), 80), '');

  IF v_nombre IS NULL AND v_cliente_id IS NOT NULL THEN
    SELECT c.nombre INTO v_nombre FROM public.clientes_web c WHERE c.id = v_cliente_id;
  END IF;

  -- Código único de 6 caracteres
  LOOP
    v_intento := v_intento + 1;
    SELECT string_agg(substr(v_alfabeto, 1 + floor(random() * length(v_alfabeto))::int, 1), '')
    INTO v_codigo
    FROM generate_series(1, 6);

    EXIT WHEN NOT EXISTS (SELECT 1 FROM public.ordenes_tienda o WHERE o.codigo = v_codigo);

    IF v_intento > 20 THEN
      RAISE EXCEPTION 'No se pudo generar el código de la orden. Intentá de nuevo.';
    END IF;
  END LOOP;

  INSERT INTO public.ordenes_tienda (codigo, cliente_web_id, cliente_nombre)
  VALUES (v_codigo, v_cliente_id, v_nombre)
  RETURNING id, ordenes_tienda.expira_at INTO v_orden_id, v_expira;

  FOR v_item IN SELECT * FROM jsonb_array_elements(p_items)
  LOOP
    v_producto_id := nullif(v_item ->> 'producto_id', '')::bigint;
    v_cantidad := nullif(v_item ->> 'cantidad', '')::numeric;

    IF v_producto_id IS NULL OR v_cantidad IS NULL OR v_cantidad <= 0 OR v_cantidad > 9999 THEN
      RAISE EXCEPTION 'Hay una cantidad inválida.';
    END IF;

    SELECT * INTO v_producto
    FROM public.productos
    WHERE id = v_producto_id AND activo = true;

    IF NOT FOUND THEN
      RAISE EXCEPTION 'Uno de los productos ya no está disponible.';
    END IF;

    IF lower(trim(v_producto.unidad_medida)) = 'unidad' AND v_cantidad <> trunc(v_cantidad) THEN
      RAISE EXCEPTION 'La cantidad de % debe ser un número entero.', v_producto.nombre;
    END IF;

    SELECT coalesce(e.cantidad, 0) INTO v_existencia
    FROM public.existencias e
    WHERE e.producto_id = v_producto_id;

    IF coalesce(v_existencia, 0) < v_cantidad THEN
      RAISE EXCEPTION 'Stock insuficiente para %.', v_producto.nombre;
    END IF;

    INSERT INTO public.detalle_ordenes_tienda (orden_id, producto_id, cantidad)
    VALUES (v_orden_id, v_producto_id, v_cantidad)
    ON CONFLICT (orden_id, producto_id)
    DO UPDATE SET cantidad = detalle_ordenes_tienda.cantidad + EXCLUDED.cantidad;

    v_total := v_total + round(
      round(v_producto.precio_venta *
        (1 - public.descuento_vigente(v_producto.descuento_porcentaje, v_producto.descuento_hasta) / 100), 2)
      * v_cantidad, 2);
  END LOOP;

  UPDATE public.ordenes_tienda o
  SET total_estimado = round(v_total, 2)
  WHERE o.id = v_orden_id;

  RETURN QUERY SELECT v_codigo, round(v_total, 2), v_expira;
END;
$$;


-- ---------------------------------------------------------
-- 3. CONSULTAR ORDEN POR CÓDIGO (vendedor)
-- ---------------------------------------------------------

CREATE OR REPLACE FUNCTION public.orden_tienda_para_venta(p_codigo text)
RETURNS TABLE(
  orden_id bigint,
  codigo text,
  cliente_nombre text,
  created_at timestamptz,
  expira_at timestamptz,
  producto_id bigint,
  cantidad numeric
)
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path TO 'public', 'auth'
AS $$
DECLARE
  v_codigo text := upper(regexp_replace(coalesce(p_codigo, ''), '[^A-Za-z0-9]', '', 'g'));
  v_orden public.ordenes_tienda%ROWTYPE;
  v_venta text;
BEGIN
  IF public.current_role_code() IS DISTINCT FROM 'vendedor' THEN
    RAISE EXCEPTION 'Solo el Vendedor puede cargar órdenes de tienda.';
  END IF;

  SELECT * INTO v_orden FROM public.ordenes_tienda o WHERE o.codigo = v_codigo;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'No existe una orden con el código %.', v_codigo;
  END IF;

  IF v_orden.estado = 'facturada' THEN
    SELECT v.numero INTO v_venta FROM public.ventas v WHERE v.id = v_orden.venta_id;
    RAISE EXCEPTION 'La orden % ya se facturó en la venta %.', v_codigo, coalesce(v_venta, '(sin número)');
  END IF;

  IF v_orden.expira_at < now() THEN
    RAISE EXCEPTION 'La orden % venció. El cliente puede generar otra desde la tienda.', v_codigo;
  END IF;

  RETURN QUERY
  SELECT v_orden.id, v_orden.codigo, v_orden.cliente_nombre, v_orden.created_at, v_orden.expira_at,
         d.producto_id, d.cantidad
  FROM public.detalle_ordenes_tienda d
  WHERE d.orden_id = v_orden.id
  ORDER BY d.id;
END;
$$;


-- ---------------------------------------------------------
-- 4. FACTURAR ORDEN (vendedor)
--    Registra la venta con registrar_venta() (precio vigente
--    y descuento de inventario) y cierra la orden. El Vendedor
--    puede haber cambiado productos o cantidades a pedido del
--    cliente: se factura lo que envía.
-- ---------------------------------------------------------

CREATE OR REPLACE FUNCTION public.facturar_orden_tienda(
  p_codigo text,
  p_items jsonb,
  p_tipo_venta text DEFAULT 'contado',
  p_cliente_id bigint DEFAULT NULL,
  p_cliente_nombre text DEFAULT NULL,
  p_fecha_vencimiento date DEFAULT NULL
)
RETURNS TABLE(venta_id bigint, numero text, total numeric, estado text)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public', 'auth'
AS $$
DECLARE
  v_codigo text := upper(regexp_replace(coalesce(p_codigo, ''), '[^A-Za-z0-9]', '', 'g'));
  v_orden public.ordenes_tienda%ROWTYPE;
  v_venta record;
BEGIN
  IF public.current_role_code() IS DISTINCT FROM 'vendedor' THEN
    RAISE EXCEPTION 'Solo el Vendedor puede facturar órdenes de tienda.';
  END IF;

  SELECT * INTO v_orden
  FROM public.ordenes_tienda o
  WHERE o.codigo = v_codigo
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'No existe una orden con el código %.', v_codigo;
  END IF;

  IF v_orden.estado = 'facturada' THEN
    RAISE EXCEPTION 'La orden % ya se facturó.', v_codigo;
  END IF;

  IF v_orden.expira_at < now() THEN
    RAISE EXCEPTION 'La orden % venció.', v_codigo;
  END IF;

  SELECT * INTO v_venta
  FROM public.registrar_venta(
    p_items,
    p_tipo_venta,
    p_cliente_id,
    coalesce(nullif(trim(coalesce(p_cliente_nombre, '')), ''), v_orden.cliente_nombre),
    NULL,
    p_fecha_vencimiento,
    'Orden en tienda ' || v_codigo
  );

  UPDATE public.ordenes_tienda o
  SET estado = 'facturada',
      venta_id = v_venta.venta_id,
      facturada_por = auth.uid(),
      facturada_at = now()
  WHERE o.id = v_orden.id;

  RETURN QUERY SELECT v_venta.venta_id, v_venta.numero, v_venta.total, v_venta.estado;
END;
$$;


