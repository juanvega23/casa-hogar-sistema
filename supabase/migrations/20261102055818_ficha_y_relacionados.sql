-- ---------------------------------------------------------
-- 1. TABLAS
-- ---------------------------------------------------------

CREATE TABLE IF NOT EXISTS public.fichas_producto (
  producto_id bigint PRIMARY KEY REFERENCES public.productos(id) ON DELETE CASCADE,
  caracteristicas text,
  dimensiones text,
  modo_uso text,
  updated_at timestamptz NOT NULL DEFAULT now(),
  updated_by uuid REFERENCES auth.users(id),
  CONSTRAINT fichas_producto_largo CHECK (
    coalesce(length(caracteristicas), 0) <= 2000
    AND coalesce(length(dimensiones), 0) <= 1000
    AND coalesce(length(modo_uso), 0) <= 2000
  )
);

CREATE TABLE IF NOT EXISTS public.areas_aplicacion (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre text NOT NULL,
  orden smallint NOT NULL DEFAULT 0,
  CONSTRAINT areas_aplicacion_nombre_unique UNIQUE (nombre)
);

CREATE TABLE IF NOT EXISTS public.producto_areas (
  producto_id bigint NOT NULL REFERENCES public.productos(id) ON DELETE CASCADE,
  area_id bigint NOT NULL REFERENCES public.areas_aplicacion(id) ON DELETE CASCADE,
  PRIMARY KEY (producto_id, area_id)
);

CREATE TABLE IF NOT EXISTS public.productos_relacionados (
  producto_id bigint NOT NULL REFERENCES public.productos(id) ON DELETE CASCADE,
  relacionado_id bigint NOT NULL REFERENCES public.productos(id) ON DELETE CASCADE,
  orden smallint NOT NULL DEFAULT 0,
  PRIMARY KEY (producto_id, relacionado_id),
  CONSTRAINT productos_relacionados_distinto CHECK (producto_id <> relacionado_id)
);

