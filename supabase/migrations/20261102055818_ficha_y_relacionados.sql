-- ==========================================================
-- FICHA DEL PRODUCTO Y PRODUCTOS RELACIONADOS
-- (correcciones del profesor)
--
-- Ficha: características, dimensiones, modo de uso y áreas de
-- aplicación (M:N). La mantiene el Encargado de Compras, que
-- administra el catálogo.
--
-- Relacionados: productos complementarios que la tienda sugiere
-- en el detalle del producto y en el carrito ("completá tu
-- compra"). Decisión comercial: Responsable Comercial.
--
-- Escritura solo por funciones; la tienda lee todo con
-- detalles_catalogo_publico() (solo productos activos).
-- ==========================================================

