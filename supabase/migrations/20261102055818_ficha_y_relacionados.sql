-- ---------------------------------------------------------
-- 2. GUARDAR FICHA (Encargado de Compras)
-- ---------------------------------------------------------

CREATE OR REPLACE FUNCTION public.guardar_ficha_producto(
  p_producto_id bigint,
  p_caracteristicas text,
  p_dimensiones text,
  p_modo_uso text,
  p_areas bigint[] DEFAULT '{}'
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public', 'auth'
AS $$
BEGIN
  IF public.current_role_code() IS DISTINCT FROM 'encargado_compras' THEN
    RAISE EXCEPTION 'Solo el Encargado de Compras puede editar la ficha del producto.';
  END IF;

  IF NOT EXISTS (SELECT 1 FROM public.productos WHERE id = p_producto_id) THEN
    RAISE EXCEPTION 'El producto no existe.';
  END IF;

  IF coalesce(length(p_caracteristicas), 0) > 2000
     OR coalesce(length(p_dimensiones), 0) > 1000
     OR coalesce(length(p_modo_uso), 0) > 2000 THEN
    RAISE EXCEPTION 'La ficha es demasiado larga: características y modo de uso hasta 2000 caracteres, dimensiones hasta 1000.';
  END IF;

  IF EXISTS (
    SELECT 1 FROM unnest(coalesce(p_areas, '{}')) a(id)
    WHERE NOT EXISTS (SELECT 1 FROM public.areas_aplicacion x WHERE x.id = a.id)
  ) THEN
    RAISE EXCEPTION 'Una de las áreas de aplicación no existe.';
  END IF;

  INSERT INTO public.fichas_producto (producto_id, caracteristicas, dimensiones, modo_uso, updated_at, updated_by)
  VALUES (
    p_producto_id,
    nullif(trim(coalesce(p_caracteristicas, '')), ''),
    nullif(trim(coalesce(p_dimensiones, '')), ''),
    nullif(trim(coalesce(p_modo_uso, '')), ''),
    now(),
    auth.uid()
  )
  ON CONFLICT (producto_id) DO UPDATE
  SET caracteristicas = EXCLUDED.caracteristicas,
      dimensiones = EXCLUDED.dimensiones,
      modo_uso = EXCLUDED.modo_uso,
      updated_at = now(),
      updated_by = auth.uid();

  DELETE FROM public.producto_areas WHERE producto_id = p_producto_id;

  INSERT INTO public.producto_areas (producto_id, area_id)
  SELECT DISTINCT p_producto_id, a.id
  FROM unnest(coalesce(p_areas, '{}')) a(id);
END;
$$;


-- ---------------------------------------------------------
-- 3. GUARDAR RELACIONADOS (Responsable Comercial)
-- ---------------------------------------------------------

CREATE OR REPLACE FUNCTION public.guardar_productos_relacionados(
  p_producto_id bigint,
  p_relacionados bigint[]
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public', 'auth'
AS $$
DECLARE
  v_lista bigint[];
BEGIN
  IF public.current_role_code() IS DISTINCT FROM 'responsable_comercial' THEN
    RAISE EXCEPTION 'Solo el Responsable Comercial puede elegir los productos relacionados.';
  END IF;

  IF NOT EXISTS (SELECT 1 FROM public.productos WHERE id = p_producto_id) THEN
    RAISE EXCEPTION 'El producto no existe.';
  END IF;

  -- Sin repetidos, conservando el orden elegido
  SELECT coalesce(array_agg(id ORDER BY pos), '{}')
  INTO v_lista
  FROM (
    SELECT id, min(pos) AS pos
    FROM unnest(coalesce(p_relacionados, '{}')) WITH ORDINALITY u(id, pos)
    GROUP BY id
  ) x;

  IF cardinality(v_lista) > 8 THEN
    RAISE EXCEPTION 'Elegí como máximo 8 productos relacionados.';
  END IF;

  IF p_producto_id = ANY (v_lista) THEN
    RAISE EXCEPTION 'Un producto no puede relacionarse consigo mismo.';
  END IF;

  IF EXISTS (
    SELECT 1 FROM unnest(v_lista) u(id)
    WHERE NOT EXISTS (SELECT 1 FROM public.productos p WHERE p.id = u.id AND p.activo = true)
  ) THEN
    RAISE EXCEPTION 'Uno de los productos relacionados no existe o está inactivo.';
  END IF;

  DELETE FROM public.productos_relacionados WHERE producto_id = p_producto_id;

  INSERT INTO public.productos_relacionados (producto_id, relacionado_id, orden)
  SELECT p_producto_id, u.id, u.pos
  FROM unnest(v_lista) WITH ORDINALITY u(id, pos);
END;
$$;


-- ---------------------------------------------------------
-- 4. LECTURA PÚBLICA (tienda)
--    Una fila por producto activo que tenga ficha, áreas o
--    relacionados. Los relacionados inactivos no se devuelven.
-- ---------------------------------------------------------

CREATE OR REPLACE FUNCTION public.detalles_catalogo_publico()
RETURNS TABLE(
  producto_id bigint,
  caracteristicas text,
  dimensiones text,
  modo_uso text,
  areas text[],
  relacionados bigint[]
)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path TO 'public'
AS $$
  SELECT
    p.id,
    f.caracteristicas,
    f.dimensiones,
    f.modo_uso,
    coalesce((
      SELECT array_agg(a.nombre ORDER BY a.orden, a.nombre)
      FROM public.producto_areas pa
      JOIN public.areas_aplicacion a ON a.id = pa.area_id
      WHERE pa.producto_id = p.id
    ), '{}'),
    coalesce((
      SELECT array_agg(r.relacionado_id ORDER BY r.orden)
      FROM public.productos_relacionados r
      JOIN public.productos rp ON rp.id = r.relacionado_id AND rp.activo = true
      WHERE r.producto_id = p.id
    ), '{}')
  FROM public.productos p
  LEFT JOIN public.fichas_producto f ON f.producto_id = p.id
  WHERE p.activo = true
    AND (
      f.producto_id IS NOT NULL
      OR EXISTS (SELECT 1 FROM public.producto_areas pa WHERE pa.producto_id = p.id)
      OR EXISTS (SELECT 1 FROM public.productos_relacionados r WHERE r.producto_id = p.id)
    );
$$;


