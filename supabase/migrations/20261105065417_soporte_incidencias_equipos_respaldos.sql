CREATE OR REPLACE FUNCTION public.resumen_panel_soporte()
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public', 'auth'
AS $$
DECLARE
  v_hoy date := (now() AT TIME ZONE 'America/Managua')::date;
  v_resultado jsonb;
BEGIN
  IF coalesce(public.current_role_code(), '') NOT IN ('soporte_ti', 'gerencia') THEN
    RAISE EXCEPTION 'Solo Soporte TI y Gerencia pueden consultar este panel.';
  END IF;

  PERFORM public.cerrar_incidencias_sin_respuesta();

  SELECT jsonb_build_object(
    'incidencias', jsonb_build_object(
      'abiertas', count(*) FILTER (WHERE estado = 'abierta'),
      'en_atencion', count(*) FILTER (WHERE estado = 'en_atencion'),
      'por_confirmar', count(*) FILTER (WHERE estado = 'resuelta'),
      'alta_pendientes', count(*) FILTER (WHERE estado IN ('abierta', 'en_atencion') AND prioridad = 'alta'),
      'horas_promedio', round((avg(extract(epoch FROM resuelta_at - created_at) / 3600) FILTER (WHERE resuelta_at IS NOT NULL))::numeric, 1),
      'por_modulo', coalesce((
        SELECT jsonb_agg(jsonb_build_object('modulo', x.modulo, 'total', x.total) ORDER BY x.total DESC, x.modulo)
        FROM (
          SELECT coalesce(i.modulo, 'Sin módulo') AS modulo, count(*) AS total
          FROM public.incidencias i
          GROUP BY 1
          ORDER BY 2 DESC, 1
          LIMIT 5
        ) x
      ), '[]'::jsonb)
    )
  )
  INTO v_resultado
  FROM public.incidencias;

  v_resultado := v_resultado || (
    SELECT jsonb_build_object(
      'equipos', jsonb_build_object(
        'total', count(*) FILTER (WHERE estado <> 'baja'),
        'por_adquirir', count(*) FILTER (WHERE estado = 'por_adquirir'),
        'disponibles', count(*) FILTER (WHERE estado = 'disponible'),
        'asignados', count(*) FILTER (WHERE estado = 'asignado'),
        'en_reparacion', count(*) FILTER (WHERE estado = 'en_reparacion'),
        'garantia_por_vencer', count(*) FILTER (
          WHERE estado NOT IN ('baja', 'por_adquirir')
            AND garantia_hasta BETWEEN v_hoy AND v_hoy + 30
        )
      )
    )
    FROM public.equipos_ti
  );

  v_resultado := v_resultado || (
    SELECT jsonb_build_object(
      'respaldos', jsonb_build_object(
        'ultima_copia', max(fecha) FILTER (WHERE tipo = 'copia' AND resultado = 'exitoso'),
        'dias_sin_copia', v_hoy - max(fecha) FILTER (WHERE tipo = 'copia' AND resultado = 'exitoso'),
        'ultima_prueba', max(fecha) FILTER (WHERE tipo = 'restauracion'),
        'pruebas_realizadas', count(*) FILTER (WHERE tipo = 'restauracion'),
        'pruebas_exitosas', count(*) FILTER (WHERE tipo = 'restauracion' AND resultado = 'exitoso')
      )
    )
    FROM public.respaldos_ti
  );

  RETURN v_resultado;
END;
$$;


