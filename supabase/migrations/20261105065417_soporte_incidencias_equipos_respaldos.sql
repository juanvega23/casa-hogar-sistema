CREATE OR REPLACE FUNCTION public.registrar_respaldo(
  p_fecha date,
  p_tipo text,
  p_destino text,
  p_resultado text,
  p_duracion_minutos integer DEFAULT NULL,
  p_observaciones text DEFAULT NULL
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public', 'auth'
AS $$
DECLARE
  v_destino text := btrim(coalesce(p_destino, ''));
  v_observaciones text := nullif(btrim(coalesce(p_observaciones, '')), '');
  v_id bigint;
BEGIN
  IF public.current_role_code() IS DISTINCT FROM 'soporte_ti' THEN
    RAISE EXCEPTION 'Solo Soporte TI registra los respaldos.';
  END IF;

  IF p_fecha IS NULL OR p_fecha > (now() AT TIME ZONE 'America/Managua')::date THEN
    RAISE EXCEPTION 'La fecha no puede ser futura.';
  END IF;

  IF coalesce(p_tipo, '') NOT IN ('copia', 'restauracion') THEN
    RAISE EXCEPTION 'Selecciona el tipo de registro.';
  END IF;

  IF length(v_destino) < 2 THEN
    RAISE EXCEPTION 'Indica dónde está la copia.';
  END IF;

  IF coalesce(p_resultado, '') NOT IN ('exitoso', 'fallido') THEN
    RAISE EXCEPTION 'Indica el resultado.';
  END IF;

  IF p_resultado = 'fallido' AND (v_observaciones IS NULL OR length(v_observaciones) < 3) THEN
    RAISE EXCEPTION 'Cuenta qué falló en las observaciones.';
  END IF;

  IF p_duracion_minutos IS NOT NULL AND p_duracion_minutos < 0 THEN
    RAISE EXCEPTION 'La duración no puede ser negativa.';
  END IF;

  INSERT INTO public.respaldos_ti (fecha, tipo, destino, resultado, duracion_minutos, observaciones, registrado_por)
  VALUES (p_fecha, p_tipo, v_destino, p_resultado, p_duracion_minutos, v_observaciones, auth.uid())
  RETURNING id INTO v_id;

  RETURN v_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.listar_respaldos()
RETURNS TABLE(
  id bigint,
  fecha date,
  tipo text,
  destino text,
  resultado text,
  duracion_minutos integer,
  observaciones text,
  registrado_nombre text
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public', 'auth'
AS $$
#variable_conflict use_column
BEGIN
  IF coalesce(public.current_role_code(), '') NOT IN ('soporte_ti', 'gerencia') THEN
    RAISE EXCEPTION 'Solo Soporte TI y Gerencia pueden consultar los respaldos.';
  END IF;

  RETURN QUERY
  SELECT r.id, r.fecha, r.tipo, r.destino, r.resultado, r.duracion_minutos, r.observaciones, p.nombre_completo::text
