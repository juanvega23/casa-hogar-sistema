$$;

-- Personal activo al que se le puede asignar un equipo
CREATE OR REPLACE FUNCTION public.personal_para_equipos()
RETURNS TABLE(id uuid, nombre text, rol text)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public', 'auth'
AS $$
#variable_conflict use_column
BEGIN
  IF public.current_role_code() IS DISTINCT FROM 'soporte_ti' THEN
    RAISE EXCEPTION 'Solo Soporte TI asigna equipos.';
  END IF;

  RETURN QUERY
  SELECT p.id, p.nombre_completo::text, r.nombre::text
  FROM public.profiles p
