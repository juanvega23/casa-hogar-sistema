$$;

CREATE OR REPLACE FUNCTION public.guardar_equipo_ti(
  p_id bigint,
  p_tipo text,
  p_descripcion text,
  p_numero_serie text,
  p_fecha_compra date,
  p_costo numeric,
  p_garantia_hasta date,
  p_destino text
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public', 'auth'
AS $$
DECLARE
  v_descripcion text := btrim(coalesce(p_descripcion, ''));
  v_serie text := nullif(btrim(coalesce(p_numero_serie, '')), '');
  v_id bigint := p_id;
BEGIN
  IF public.current_role_code() IS DISTINCT FROM 'soporte_ti' THEN
    RAISE EXCEPTION 'Solo Soporte TI administra los equipos.';
  END IF;

  IF length(v_descripcion) < 3 THEN
    RAISE EXCEPTION 'Escribe la marca y el modelo del equipo.';
  END IF;

  IF coalesce(p_tipo, '') NOT IN ('laptop', 'computadora', 'ups', 'impresora', 'red', 'otro') THEN
    RAISE EXCEPTION 'Selecciona el tipo de equipo.';
  END IF;

  IF p_costo IS NOT NULL AND p_costo < 0 THEN
    RAISE EXCEPTION 'El costo no puede ser negativo.';
  END IF;

  IF p_fecha_compra IS NOT NULL AND p_garantia_hasta IS NOT NULL AND p_garantia_hasta < p_fecha_compra THEN
    RAISE EXCEPTION 'La garantía no puede terminar antes de la compra.';
  END IF;

  IF v_serie IS NOT NULL AND EXISTS (
    SELECT 1 FROM public.equipos_ti e
    WHERE upper(e.numero_serie) = upper(v_serie) AND e.id IS DISTINCT FROM v_id
  ) THEN
    RAISE EXCEPTION 'Ya existe un equipo con el número de serie %.', v_serie;
  END IF;

  IF v_id IS NULL THEN
    INSERT INTO public.equipos_ti (tipo, descripcion, numero_serie, fecha_compra, costo, garantia_hasta, destino, estado)
    VALUES (p_tipo, v_descripcion, v_serie, p_fecha_compra, p_costo, p_garantia_hasta, nullif(btrim(coalesce(p_destino, '')), ''), 'disponible')
    RETURNING id INTO v_id;

    INSERT INTO public.historial_equipos_ti (equipo_id, accion, usuario_id)
    VALUES (v_id, 'Registrado', auth.uid());
  ELSE
    UPDATE public.equipos_ti e
    SET tipo = p_tipo,
        descripcion = v_descripcion,
        numero_serie = v_serie,
        fecha_compra = p_fecha_compra,
        costo = p_costo,
        garantia_hasta = p_garantia_hasta,
        destino = nullif(btrim(coalesce(p_destino, '')), ''),
        updated_at = now()
    WHERE e.id = v_id;

    IF NOT FOUND THEN
      RAISE EXCEPTION 'El equipo indicado no existe.';
    END IF;

    INSERT INTO public.historial_equipos_ti (equipo_id, accion, usuario_id)
    VALUES (v_id, 'Datos actualizados', auth.uid());
  END IF;

  RETURN v_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.cambiar_estado_equipo_ti(
  p_id bigint,
  p_estado text,
  p_responsable_id uuid DEFAULT NULL,
  p_motivo text DEFAULT NULL
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public', 'auth'
AS $$
DECLARE
  v_motivo text := nullif(btrim(coalesce(p_motivo, '')), '');
  v_equipo public.equipos_ti%ROWTYPE;
  v_responsable text;
BEGIN
  IF public.current_role_code() IS DISTINCT FROM 'soporte_ti' THEN
    RAISE EXCEPTION 'Solo Soporte TI administra los equipos.';
  END IF;

  IF coalesce(p_estado, '') NOT IN ('disponible', 'asignado', 'en_reparacion', 'baja') THEN
    RAISE EXCEPTION 'El estado no es válido.';
  END IF;

  SELECT * INTO v_equipo FROM public.equipos_ti e WHERE e.id = p_id FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'El equipo indicado no existe.';
  END IF;

  IF v_equipo.estado = 'baja' THEN
    RAISE EXCEPTION 'El equipo % está dado de baja.', v_equipo.codigo;
  END IF;

  IF p_estado = 'asignado' THEN
    SELECT p.nombre_completo INTO v_responsable
    FROM public.profiles p
    WHERE p.id = p_responsable_id AND p.activo;

    IF NOT FOUND THEN
      RAISE EXCEPTION 'Selecciona a un empleado activo como responsable.';
    END IF;
  END IF;

  IF p_estado IN ('baja', 'en_reparacion') AND (v_motivo IS NULL OR length(v_motivo) < 3) THEN
    RAISE EXCEPTION 'Indica el motivo.';
  END IF;

  UPDATE public.equipos_ti e
  SET estado = p_estado,
      responsable_id = CASE
        WHEN p_estado = 'asignado' THEN p_responsable_id
        WHEN p_estado = 'en_reparacion' THEN e.responsable_id
        ELSE NULL
      END,
      updated_at = now()
  WHERE e.id = p_id;

  INSERT INTO public.historial_equipos_ti (equipo_id, accion, detalle, usuario_id)
  VALUES (
    p_id,
    CASE p_estado
      WHEN 'disponible' THEN 'Disponible'
      WHEN 'asignado' THEN 'Asignado'
      WHEN 'en_reparacion' THEN 'En reparación'
      ELSE 'Dado de baja'
    END,
    concat_ws(' · ', CASE WHEN v_responsable IS NOT NULL THEN 'A ' || v_responsable END, v_motivo),
    auth.uid()
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.historial_equipo_ti(p_id bigint)
RETURNS TABLE(accion text, detalle text, usuario text, created_at timestamptz)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public', 'auth'
AS $$
#variable_conflict use_column
BEGIN
  IF coalesce(public.current_role_code(), '') NOT IN ('soporte_ti', 'gerencia') THEN
    RAISE EXCEPTION 'Solo Soporte TI y Gerencia pueden consultar los equipos.';
  END IF;

  RETURN QUERY
  SELECT h.accion, h.detalle, coalesce(p.nombre_completo::text, 'Sistema'), h.created_at
  FROM public.historial_equipos_ti h
  LEFT JOIN public.profiles p ON p.id = h.usuario_id
  WHERE h.equipo_id = p_id
  ORDER BY h.created_at, h.id;
END;
$$;


