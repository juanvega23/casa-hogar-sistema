CREATE OR REPLACE FUNCTION public.listar_equipos_ti()
RETURNS TABLE(
  id bigint,
  codigo text,
  tipo text,
  descripcion text,
  numero_serie text,
  fecha_compra date,
  costo numeric,
  garantia_hasta date,
  estado text,
  responsable_id uuid,
  responsable_nombre text,
  destino text,
  incidencias bigint
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public', 'auth'
AS $$
#variable_conflict use_column
BEGIN
  IF coalesce(public.current_role_code(), '') NOT IN ('soporte_ti', 'gerencia') THEN
    RAISE EXCEPTION 'Solo Soporte TI y Gerencia pueden consultar los equipos.';
  END IF;

  RETURN QUERY
