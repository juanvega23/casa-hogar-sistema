-- Resueltas sin respuesta en 3 días: se cierran solas
CREATE OR REPLACE FUNCTION public.cerrar_incidencias_sin_respuesta()
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public', 'auth'
AS $$
BEGIN
  WITH cerradas AS (
    UPDATE public.incidencias i
    SET estado = 'cerrada', cerrada_at = now(), updated_at = now()
    WHERE i.estado = 'resuelta' AND i.resuelta_at < now() - interval '3 days'
    RETURNING i.id
  )
  INSERT INTO public.historial_incidencias (incidencia_id, accion, detalle)
  SELECT c.id, 'Cerrada', 'Sin respuesta de quien la reportó en 3 días.'
  FROM cerradas c;
END;
$$;

CREATE OR REPLACE FUNCTION public.reportar_incidencia(
  p_descripcion text,
  p_modulo text,
  p_tipo text,
  p_impacto text
)
RETURNS TABLE(incidencia_id bigint, numero text)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public', 'auth'
AS $$
#variable_conflict use_column
DECLARE
  v_usuario uuid := auth.uid();
  v_descripcion text := btrim(coalesce(p_descripcion, ''));
  v_id bigint;
  v_numero text;
BEGIN
  IF v_usuario IS NULL OR public.current_role_code() IS NULL THEN
    RAISE EXCEPTION 'Solo el personal puede reportar incidencias.';
  END IF;

  IF length(v_descripcion) < 5 THEN
    RAISE EXCEPTION 'Describe el problema con un poco más de detalle.';
  END IF;

  IF coalesce(p_tipo, '') NOT IN ('sistema', 'equipo', 'acceso', 'red') THEN
    RAISE EXCEPTION 'Selecciona el tipo de problema.';
  END IF;

  IF coalesce(p_impacto, '') NOT IN ('bloquea', 'parcial', 'no') THEN
    RAISE EXCEPTION 'Indica si el problema te impide trabajar.';
  END IF;

  INSERT INTO public.incidencias (descripcion, modulo, tipo, impacto, prioridad, reportado_por)
  VALUES (
    v_descripcion,
    nullif(btrim(coalesce(p_modulo, '')), ''),
    p_tipo,
    p_impacto,
    CASE p_impacto WHEN 'bloquea' THEN 'alta' WHEN 'parcial' THEN 'media' ELSE 'baja' END,
    v_usuario
  )
  RETURNING id, incidencias.numero INTO v_id, v_numero;

  INSERT INTO public.historial_incidencias (incidencia_id, accion, usuario_id)
  VALUES (v_id, 'Reportada', v_usuario);

  RETURN QUERY SELECT v_id, v_numero;
END;
$$;

CREATE OR REPLACE FUNCTION public.mis_incidencias()
RETURNS TABLE(
  id bigint,
  numero text,
  descripcion text,
  modulo text,
  tipo text,
  impacto text,
  prioridad text,
  estado text,
  solucion text,
  atendido_nombre text,
  created_at timestamptz,
  resuelta_at timestamptz
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public', 'auth'
AS $$
#variable_conflict use_column
BEGIN
  IF auth.uid() IS NULL OR public.current_role_code() IS NULL THEN
    RAISE EXCEPTION 'Solo el personal puede consultar sus incidencias.';
  END IF;

  PERFORM public.cerrar_incidencias_sin_respuesta();

  RETURN QUERY
  SELECT i.id, i.numero, i.descripcion, i.modulo, i.tipo, i.impacto, i.prioridad, i.estado,
         i.solucion, a.nombre_completo::text, i.created_at, i.resuelta_at
  FROM public.incidencias i
  LEFT JOIN public.profiles a ON a.id = i.atendido_por
  WHERE i.reportado_por = auth.uid()
  ORDER BY i.created_at DESC, i.id DESC;
END;
$$;

-- Lo más urgente primero; lo cerrado al final
CREATE OR REPLACE FUNCTION public.listar_incidencias()
RETURNS TABLE(
  id bigint,
  numero text,
  descripcion text,
  modulo text,
  tipo text,
  impacto text,
  prioridad text,
  estado text,
  solucion text,
  equipo_id bigint,
  equipo_codigo text,
  reportado_nombre text,
  atendido_nombre text,
  created_at timestamptz,
  resuelta_at timestamptz,
  cerrada_at timestamptz
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public', 'auth'
AS $$
#variable_conflict use_column
BEGIN
  IF coalesce(public.current_role_code(), '') NOT IN ('soporte_ti', 'gerencia') THEN
    RAISE EXCEPTION 'Solo Soporte TI y Gerencia pueden consultar las incidencias.';
  END IF;

  PERFORM public.cerrar_incidencias_sin_respuesta();

  RETURN QUERY
  SELECT i.id, i.numero, i.descripcion, i.modulo, i.tipo, i.impacto, i.prioridad, i.estado, i.solucion,
         i.equipo_id, e.codigo, r.nombre_completo::text, a.nombre_completo::text,
         i.created_at, i.resuelta_at, i.cerrada_at
  FROM public.incidencias i
  LEFT JOIN public.equipos_ti e ON e.id = i.equipo_id
  LEFT JOIN public.profiles r ON r.id = i.reportado_por
  LEFT JOIN public.profiles a ON a.id = i.atendido_por
  ORDER BY
    CASE i.estado WHEN 'abierta' THEN 1 WHEN 'en_atencion' THEN 2 WHEN 'resuelta' THEN 3 ELSE 4 END,
    CASE i.prioridad WHEN 'alta' THEN 1 WHEN 'media' THEN 2 ELSE 3 END,
    i.created_at;
END;
$$;

CREATE OR REPLACE FUNCTION public.historial_incidencia(p_incidencia_id bigint)
RETURNS TABLE(accion text, detalle text, usuario text, created_at timestamptz)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public', 'auth'
AS $$
#variable_conflict use_column
BEGIN
  IF coalesce(public.current_role_code(), '') NOT IN ('soporte_ti', 'gerencia')
     AND NOT EXISTS (
       SELECT 1 FROM public.incidencias i
       WHERE i.id = p_incidencia_id AND i.reportado_por = auth.uid() AND public.current_role_code() IS NOT NULL
     ) THEN
    RAISE EXCEPTION 'No tienes acceso a esta incidencia.';
  END IF;

  RETURN QUERY
  SELECT h.accion, h.detalle, coalesce(p.nombre_completo::text, 'Sistema'), h.created_at
  FROM public.historial_incidencias h
  LEFT JOIN public.profiles p ON p.id = h.usuario_id
  WHERE h.incidencia_id = p_incidencia_id
  ORDER BY h.created_at, h.id;
END;
$$;

CREATE OR REPLACE FUNCTION public.atender_incidencia(
  p_incidencia_id bigint,
  p_prioridad text,
  p_equipo_id bigint DEFAULT NULL
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public', 'auth'
AS $$
DECLARE
  v_incidencia public.incidencias%ROWTYPE;
  v_equipo text;
BEGIN
  IF public.current_role_code() IS DISTINCT FROM 'soporte_ti' THEN
    RAISE EXCEPTION 'Solo Soporte TI atiende incidencias.';
  END IF;

  IF coalesce(p_prioridad, '') NOT IN ('alta', 'media', 'baja') THEN
    RAISE EXCEPTION 'La prioridad no es válida.';
  END IF;

  SELECT * INTO v_incidencia FROM public.incidencias i WHERE i.id = p_incidencia_id FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'La incidencia indicada no existe.';
  END IF;

  IF v_incidencia.estado <> 'abierta' THEN
    RAISE EXCEPTION 'La incidencia % ya no está abierta.', v_incidencia.numero;
  END IF;

  IF p_equipo_id IS NOT NULL THEN
    SELECT e.codigo INTO v_equipo FROM public.equipos_ti e WHERE e.id = p_equipo_id;

    IF NOT FOUND THEN
      RAISE EXCEPTION 'El equipo indicado no existe.';
    END IF;
  END IF;

  UPDATE public.incidencias i
  SET estado = 'en_atencion',
      prioridad = p_prioridad,
      equipo_id = p_equipo_id,
      atendido_por = auth.uid(),
      atendida_at = now(),
      updated_at = now()
  WHERE i.id = p_incidencia_id;

  INSERT INTO public.historial_incidencias (incidencia_id, accion, detalle, usuario_id)
  VALUES (
    p_incidencia_id,
    'En atención',
    concat_ws(' · ',
      CASE WHEN p_prioridad <> v_incidencia.prioridad THEN 'Prioridad: ' || p_prioridad END,
      CASE WHEN v_equipo IS NOT NULL THEN 'Equipo: ' || v_equipo END
    ),
    auth.uid()
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.agregar_nota_incidencia(p_incidencia_id bigint, p_nota text)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public', 'auth'
AS $$
DECLARE
  v_nota text := btrim(coalesce(p_nota, ''));
  v_estado text;
BEGIN
  IF public.current_role_code() IS DISTINCT FROM 'soporte_ti' THEN
    RAISE EXCEPTION 'Solo Soporte TI agrega notas.';
  END IF;

  IF length(v_nota) < 3 THEN
    RAISE EXCEPTION 'Escribe la nota.';
  END IF;

  SELECT i.estado INTO v_estado FROM public.incidencias i WHERE i.id = p_incidencia_id;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'La incidencia indicada no existe.';
  END IF;

  IF v_estado = 'cerrada' THEN
    RAISE EXCEPTION 'La incidencia ya está cerrada.';
  END IF;

  INSERT INTO public.historial_incidencias (incidencia_id, accion, detalle, usuario_id)
  VALUES (p_incidencia_id, 'Nota', v_nota, auth.uid());
END;
$$;

CREATE OR REPLACE FUNCTION public.resolver_incidencia(p_incidencia_id bigint, p_solucion text)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public', 'auth'
AS $$
DECLARE
  v_solucion text := btrim(coalesce(p_solucion, ''));
  v_incidencia public.incidencias%ROWTYPE;
BEGIN
  IF public.current_role_code() IS DISTINCT FROM 'soporte_ti' THEN
    RAISE EXCEPTION 'Solo Soporte TI resuelve incidencias.';
  END IF;

  IF length(v_solucion) < 5 THEN
    RAISE EXCEPTION 'Escribe qué se hizo para resolverla.';
  END IF;

  SELECT * INTO v_incidencia FROM public.incidencias i WHERE i.id = p_incidencia_id FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'La incidencia indicada no existe.';
  END IF;

  IF v_incidencia.estado <> 'en_atencion' THEN
    RAISE EXCEPTION 'La incidencia % debe estar en atención para resolverla.', v_incidencia.numero;
  END IF;

  UPDATE public.incidencias i
  SET estado = 'resuelta', solucion = v_solucion, resuelta_at = now(), updated_at = now()
  WHERE i.id = p_incidencia_id;

  INSERT INTO public.historial_incidencias (incidencia_id, accion, detalle, usuario_id)
  VALUES (p_incidencia_id, 'Resuelta', v_solucion, auth.uid());
END;
$$;

-- Quien la reportó confirma, o la devuelve explicando qué sigue mal
CREATE OR REPLACE FUNCTION public.confirmar_incidencia(
  p_incidencia_id bigint,
  p_resuelta boolean,
  p_comentario text DEFAULT NULL
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public', 'auth'
AS $$
DECLARE
  v_comentario text := nullif(btrim(coalesce(p_comentario, '')), '');
  v_incidencia public.incidencias%ROWTYPE;
BEGIN
  IF auth.uid() IS NULL OR public.current_role_code() IS NULL THEN
    RAISE EXCEPTION 'Usuario no autenticado.';
  END IF;

  SELECT * INTO v_incidencia FROM public.incidencias i WHERE i.id = p_incidencia_id FOR UPDATE;

  IF NOT FOUND OR v_incidencia.reportado_por <> auth.uid() THEN
    RAISE EXCEPTION 'Solo quien reportó la incidencia puede confirmarla.';
  END IF;

  IF v_incidencia.estado <> 'resuelta' THEN
    RAISE EXCEPTION 'La incidencia % no está esperando confirmación.', v_incidencia.numero;
  END IF;

  IF p_resuelta THEN
    UPDATE public.incidencias i
    SET estado = 'cerrada', cerrada_at = now(), updated_at = now()
    WHERE i.id = p_incidencia_id;

    INSERT INTO public.historial_incidencias (incidencia_id, accion, detalle, usuario_id)
    VALUES (p_incidencia_id, 'Cerrada', coalesce(v_comentario, 'Confirmó que quedó resuelta.'), auth.uid());
  ELSE
    IF v_comentario IS NULL OR length(v_comentario) < 3 THEN
      RAISE EXCEPTION 'Cuenta qué sigue fallando.';
    END IF;

    UPDATE public.incidencias i
    SET estado = 'en_atencion', solucion = NULL, resuelta_at = NULL, updated_at = now()
    WHERE i.id = p_incidencia_id;

    INSERT INTO public.historial_incidencias (incidencia_id, accion, detalle, usuario_id)
    VALUES (p_incidencia_id, 'Reabierta', v_comentario, auth.uid());
  END IF;
END;
$$;


