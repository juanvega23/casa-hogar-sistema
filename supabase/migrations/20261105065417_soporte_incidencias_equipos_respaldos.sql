CREATE SEQUENCE IF NOT EXISTS public.incidencia_numero_seq;
CREATE SEQUENCE IF NOT EXISTS public.equipo_ti_numero_seq;

CREATE TABLE IF NOT EXISTS public.equipos_ti (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo text NOT NULL DEFAULT 'EQ-' || lpad(nextval('public.equipo_ti_numero_seq')::text, 4, '0'),
  tipo text NOT NULL,
  descripcion text NOT NULL,
  numero_serie text,
  fecha_compra date,
  costo numeric(14,2),
  garantia_hasta date,
  estado text NOT NULL DEFAULT 'disponible',
  responsable_id uuid REFERENCES public.profiles(id),
  destino text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT equipos_ti_codigo_unique UNIQUE (codigo),
  CONSTRAINT equipos_ti_tipo_check CHECK (tipo IN ('laptop', 'computadora', 'ups', 'impresora', 'red', 'otro')),
  CONSTRAINT equipos_ti_estado_check CHECK (estado IN ('por_adquirir', 'disponible', 'asignado', 'en_reparacion', 'baja')),
  CONSTRAINT equipos_ti_costo_check CHECK (costo IS NULL OR costo >= 0),
  CONSTRAINT equipos_ti_asignado_check CHECK (estado <> 'asignado' OR responsable_id IS NOT NULL)
);

CREATE UNIQUE INDEX IF NOT EXISTS equipos_ti_numero_serie_unique
  ON public.equipos_ti (upper(numero_serie))
  WHERE numero_serie IS NOT NULL;

CREATE TABLE IF NOT EXISTS public.historial_equipos_ti (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  equipo_id bigint NOT NULL REFERENCES public.equipos_ti(id),
  accion text NOT NULL,
  detalle text,
  usuario_id uuid REFERENCES auth.users(id),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS historial_equipos_ti_equipo_idx
  ON public.historial_equipos_ti (equipo_id, created_at);

CREATE TABLE IF NOT EXISTS public.incidencias (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  numero text NOT NULL DEFAULT 'INC-' || lpad(nextval('public.incidencia_numero_seq')::text, 6, '0'),
  descripcion text NOT NULL,
  modulo text,
  tipo text NOT NULL,
  impacto text NOT NULL,
  prioridad text NOT NULL,
  estado text NOT NULL DEFAULT 'abierta',
  solucion text,
  equipo_id bigint REFERENCES public.equipos_ti(id),
  reportado_por uuid NOT NULL REFERENCES auth.users(id),
  atendido_por uuid REFERENCES auth.users(id),
  created_at timestamptz NOT NULL DEFAULT now(),
  atendida_at timestamptz,
  resuelta_at timestamptz,
  cerrada_at timestamptz,
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT incidencias_numero_unique UNIQUE (numero),
  CONSTRAINT incidencias_descripcion_check CHECK (length(btrim(descripcion)) >= 5),
  CONSTRAINT incidencias_tipo_check CHECK (tipo IN ('sistema', 'equipo', 'acceso', 'red')),
  CONSTRAINT incidencias_impacto_check CHECK (impacto IN ('bloquea', 'parcial', 'no')),
  CONSTRAINT incidencias_prioridad_check CHECK (prioridad IN ('alta', 'media', 'baja')),
  CONSTRAINT incidencias_estado_check CHECK (estado IN ('abierta', 'en_atencion', 'resuelta', 'cerrada'))
