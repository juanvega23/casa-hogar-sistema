-- ==========================================================
-- SOPORTE TI: INCIDENCIAS, EQUIPOS Y RESPALDOS
--
-- Funciones del Técnico de Soporte según el presupuesto de TI:
--
--   Incidencias: cualquier empleado reporta un problema; Soporte
--     lo atiende y lo resuelve; quien reportó confirma. Sin
--     respuesta en 3 días, se cierra sola.
--       abierta → en_atencion → resuelta → cerrada
--   Equipos: inventario de equipos de TI, con responsable,
--     garantía e historial.
--   Respaldos: bitácora de copias y pruebas de restauración.
--     Registra el resultado; no ejecuta la copia.
--
-- Soporte gestiona y Gerencia consulta. Las tablas no tienen
-- acceso directo: todo pasa por funciones que validan el rol y
-- dejan historial. No se puede borrar nada.
-- ==========================================================

BEGIN;


