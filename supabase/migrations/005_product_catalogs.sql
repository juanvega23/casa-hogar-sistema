-- ============================================================
-- 6. TRIGGERS UPDATED_AT
-- ============================================================

drop trigger if exists set_marcas_updated_at
on public.marcas;

create trigger set_marcas_updated_at
before update on public.marcas
for each row
execute function public.set_updated_at();


